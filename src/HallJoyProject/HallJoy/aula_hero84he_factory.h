inline std::uint16_t DecodeAssignment(std::uint32_t value) noexcept {
    if (value == 0x0D000000u) return 0x409; // Vendor Fn1 action.
    if (value <= 0xE7u) return static_cast<std::uint16_t>(value);
    const auto mask = value >> 16;
    if (value != (mask << 16) || !mask || mask > 128 || (mask & (mask - 1))) return 0;
    std::uint16_t hid = 0xE0;
    for (auto bits = mask; bits > 1; bits >>= 1) ++hid;
    return hid;
}
