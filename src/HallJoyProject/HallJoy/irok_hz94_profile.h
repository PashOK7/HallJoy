inline constexpr bool WitmodProduct(unsigned pid) noexcept
{
    return pid == 0x7372 || pid == 0x7402 || (pid >= 0x7472 && pid <= 0x7474);
}

inline bool Matches(const irok_nd75::DeviceInfo& identity) noexcept
{
    std::string_view product(identity.product.data());
    while (!product.empty() && product.back() == ' ') product.remove_suffix(1);
    return product == "7187_AUSXHERGB";
}

inline constexpr std::uint16_t HostCode(std::uint8_t hid) noexcept
{
    return hid == 0xfa ? halljoy::keycode::kFn : hid;
}

struct MapEvidence
{
    unsigned assigned = 0, factory = 0, outside = 0;
    bool Admitted() const noexcept { return assigned >= 60 && outside == 0; }
};

inline MapEvidence InspectMap(const irok_nd75::PositionToHid& map) noexcept
{
    MapEvidence evidence{};
    for (std::size_t pos = 0; pos < map.size(); ++pos)
    {
        if (!map[pos]) continue;
        ++evidence.assigned;
        evidence.factory += map[pos] == kFactoryMap[pos];
        evidence.outside += kFactoryMap[pos] == 0;
    }
    return evidence;
}
