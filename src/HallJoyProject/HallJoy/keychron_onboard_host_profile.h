inline int SlotForHid(std::uint16_t hid) noexcept {
    if (!hid) return HJO_UNBOUND;
    for (unsigned i=0;i<HJO_SLOTS;++i) if (kSlotHid[i]==hid) return static_cast<int>(i);
    return -1;
}
