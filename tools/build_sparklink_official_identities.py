#!/usr/bin/env python3
"""Generate sparklink_official_identities.h from the reviewed identity list.

The list contains identifiers only (VID, PID) taken from the SparkLink PlayJoy
official keyboard list. Use --check to verify the committed header.
"""
import argparse, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / 'docs/research/sparklink-v2-official-identities-20261012.json'
DST = ROOT / 'src/HallJoyProject/HallJoy/sparklink_official_identities.h'
EXCLUDED_VIDS = {0x3151}  # RongYuan / Attack Shark: different protocol on shared IDs


def render() -> str:
    doc = json.loads(SRC.read_text(encoding='utf-8'))
    ids = sorted({(int(e['vid'], 16) << 16) | int(e['pid'], 16)
                  for e in doc['identities'] if int(e['vid'], 16) not in EXCLUDED_VIDS})
    lines = [
        '// Generated by tools/build_sparklink_official_identities.py. Do not edit.',
        '// Source: docs/research/sparklink-v2-official-identities-20261012.json',
        '#pragma once',
        '#include <array>',
        '#include <cstddef>',
        '#include <cstdint>',
        'namespace halljoy::sparklink {',
        '// Sorted (vid<<16)|pid of keyboards the SparkLink PlayJoy driver lists for',
        '// usage page 0xFFB0 usage 1. VID 0x3151 is excluded on purpose.',
        f'inline constexpr std::array<std::uint32_t,{len(ids)}> kOfficialIdentities{{{{',
    ]
    row = ' '
    for i, v in enumerate(ids):
        item = f'0x{v:08X}u,'
        if len(row) + len(item) + 1 > 118:
            lines.append(row.rstrip())
            row = ' '
        row += ' ' + item
    lines.append(row.rstrip())
    lines.append('}};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = render()
    if args.check:
        current = DST.read_bytes().decode('utf-8') if DST.exists() else ''
        if current != text:
            print('sparklink_official_identities.h is stale; run tools/build_sparklink_official_identities.py')
            return 1
        print('SPARKLINK_OFFICIAL_IDENTITIES=PASS')
        return 0
    DST.write_bytes(text.encode('utf-8'))
    print(f'wrote {DST.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
