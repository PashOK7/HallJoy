"""Render reviewed Corsair protocol facts; no vendor assets or network required."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'docs/development/corsair_vanguard_protocol.json'
OUTPUT=ROOT/'src/HallJoyProject/HallJoy/generated/corsair_vanguard_data.h'
def render(d):
 def row(values):return '{'+','.join(str(x) for x in values)+'}'
 lines=['// Generated by tools/generate_corsair_vanguard.py; protocol facts, not firmware code.',
        '// Reference image SHA256: '+d['provenance']['reference_image_sha256'],
        '#pragma once','#include <cstdint>','namespace halljoy::corsair_vanguard {',
        'struct Layout { unsigned id, count; std::uint16_t hid[100]; std::uint8_t sensor[139], factoryCurve[100], overrideCurve[6][135]; };',
        'inline constexpr std::uint16_t kCurves[18][41] = {']
 for c in d['curves']:
  assert len(c)==41;lines.append('    '+row(c)+',')
 lines+=['};','inline constexpr Layout kLayouts[] = {']
 for l in d['layouts']:
  assert l['id'] in (1,2,4) and l['sensor_count']<=100
  hids=[0]*100
  for k in l['physical_keys']:
   hid=k['hid'] or {122:0x409,136:0x403}[k['code']]
   assert not hids[k['sensor']];hids[k['sensor']]=hid
  assert len(set(x for x in hids if x))==len(l['physical_keys'])
  curves=l['factory_curves']+[0]*(100-l['sensor_count'])
  overrides=[row(l['override_curves_by_switch'][str(i)]) for i in range(6)]
  lines.append('    {'+str(l['id'])+','+str(l['sensor_count'])+','+row(hids)+','+row(l['protocol_to_sensor'])+','+row(curves)+',{'+','.join(overrides)+'}},')
 lines+=['};','inline constexpr const Layout* FindLayout(unsigned id) noexcept {',
         '    for(const auto& layout:kLayouts) if(layout.id==id)return &layout;',
         '    return nullptr;','}','}']
 return '\n'.join(lines)+'\n'
def main():
 p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');a=p.parse_args()
 expected=render(json.loads(SOURCE.read_text())).encode()
 if a.write:
  old=OUTPUT.read_bytes() if OUTPUT.exists() else None
  if old is None:
   with OUTPUT.open('xb') as out:out.write(expected)
  elif old!=expected:
   assert OUTPUT.read_bytes()==old
   temp=OUTPUT.with_name(OUTPUT.name+'.new');assert not temp.exists()
   with temp.open('xb') as out:out.write(expected)
   assert OUTPUT.read_bytes()==old;temp.replace(OUTPUT)
 assert OUTPUT.read_bytes()==expected,'stale Corsair protocol data'
 print('CORSAIR_PROTOCOL_DATA=PASS')
if __name__=='__main__':main()
