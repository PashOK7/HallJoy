"""Generate the runtime 'not supported' (red) keyboard catalog and reconcile it with a live Sheet snapshot.
--write regenerates src/HallJoyProject/HallJoy/unsupported_keyboard_catalog.h from
docs/development/unsupported_keyboards.json; without it the header must already match.
--sheet takes a fresh Sheet read (native get_spreadsheet JSON with effectiveFormat, or a
derived list of {brand, model, status, color}); its red rows must equal the catalog exactly.
"""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
CATALOG=ROOT/'docs/development/unsupported_keyboards.json'
HEADER=ROOT/'src/HallJoyProject/HallJoy/unsupported_keyboard_catalog.h'
def wide(text):
    assert text.isascii() and '"' not in text and '\\' not in text,text
    return f'L"{text}"'
def render(data):
    assert data['schema']==1
    entries=[];seen=set();identities=set()
    for model in data['models']:
        key=(model['brand'],model['model'])
        assert key not in seen,key
        seen.add(key)
        assert bool(model.get('usb'))!=bool(model.get('undetected')),key
        for usb in model.get('usb',[]):
            vid,pid=int(usb['vid'],16),int(usb['pid'],16)
            product=usb.get('product')
            assert product is None or (product==product.strip() and product),key
            ident=(vid,pid,(product or '').upper())
            assert ident not in identities,ident
            identities.add(ident)
            entries.append((vid,pid,product,model['shown']))
    assert 0<len(entries)<255
    lines=['// Generated by tools/unsupported_keyboard_catalog.py. Edit docs/development/unsupported_keyboards.json.',
           '#pragma once','#include <string_view>','namespace halljoy::keyboard_support {',
           'struct UnsupportedKeyboard final { unsigned short vid, pid; const wchar_t* product; const wchar_t* name; };',
           '// Red Sheet rows with an exact USB identity; product is the upper-case USB product string or nullptr (any).',
           'inline constexpr UnsupportedKeyboard kUnsupportedKeyboards[] = {']
    for vid,pid,product,shown in entries:
        lines.append(f'    {{0x{vid:04X}, 0x{pid:04X}, {wide(product.upper()) if product else "nullptr"}, {wide(shown)}}},')
    lines+=['};',
            '// 1-based catalog index, 0 when the identity is not a known unsupported keyboard.',
            '// product must already be upper case (Windows bus-reported description).',
            'inline unsigned FindUnsupported(unsigned vid, unsigned pid, std::wstring_view product) noexcept {',
            '    while(!product.empty() && product.back()==L\' \') product.remove_suffix(1);',
            '    unsigned index=0;',
            '    for(const auto& k : kUnsupportedKeyboards) {',
            '        ++index;',
            '        if(k.vid==vid && k.pid==pid && (!k.product || product==k.product)) return index;',
            '    }',
            '    return 0;',
            '}',
            'inline const wchar_t* UnsupportedName(unsigned index) noexcept {',
            '    return index && index<=sizeof(kUnsupportedKeyboards)/sizeof(kUnsupportedKeyboards[0]) ? kUnsupportedKeyboards[index-1].name : nullptr;',
            '}',
            '}']
    return '\n'.join(lines)+'\n'
def sheet_red_rows(path):
    data=json.loads(Path(path).read_text(encoding='utf-8'))
    if isinstance(data,list):
        return {(r['brand'],r['model']):r['status'] for r in data
                if r.get('color',{}).get('red',0)>=.9 and r.get('color',{}).get('green',1)<.8}
    sheet=next(s for s in data.get('updatedSpreadsheet',data)['sheets']
               if s.get('properties',{}).get('title','Main')=='Main')
    result={}
    for row in sheet['data'][0].get('rowData',[])[1:]:
        cells=row.get('values',[])[:3]
        if len(cells)<3:continue
        values=[c.get('formattedValue','') for c in cells]
        color=cells[2].get('effectiveFormat',{}).get('backgroundColor',{})
        if all(values) and color.get('red',0)>=.9 and color.get('green',1)<.8:
            result[(values[0],values[1])]=values[2]
    return result
def main():
    p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');p.add_argument('--sheet',type=Path);a=p.parse_args()
    data=json.loads(CATALOG.read_text(encoding='utf-8'));expected=render(data).encode()
    if a.write and (not HEADER.exists() or HEADER.read_bytes()!=expected):HEADER.write_bytes(expected)
    assert HEADER.read_bytes()==expected,'Generated unsupported keyboard catalog differs from docs/development/unsupported_keyboards.json'
    wanted={(m['brand'],m['model']):m['status'] for m in data['models']}
    if a.sheet:
        actual=sheet_red_rows(a.sheet)
        assert actual==wanted,{'missing_or_wrong':[(k,v,actual.get(k)) for k,v in wanted.items() if actual.get(k)!=v],
                               'unexpected':[(k,v) for k,v in actual.items() if k not in wanted]}
    detected=sum(1 for m in data['models'] if m.get('usb'))
    print(f'UNSUPPORTED_KEYBOARD_CATALOG=PASS red={len(wanted)} detected={detected} live_sheet={bool(a.sheet)}')
if __name__=='__main__':main()
